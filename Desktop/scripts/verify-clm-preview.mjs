import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const output = process.env.CLM_PREVIEW_OUTPUT || 'test-results/clm-preview';
await mkdir(output, { recursive: true });
let server;
let browser;
try {
  if (!process.env.DESKTOP_PREVIEW_URL) {
    server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
    await server.listen();
  }
  const base = process.env.DESKTOP_PREVIEW_URL || server.resolvedUrls.local[0].replace(/\/$/, '');
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  const external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!['127.0.0.1', 'localhost'].includes(new URL(request.url()).hostname)) external.push(request.url()); });
  await page.goto(`${base}/tests/fixtures/clm-workspace.html`);
  await page.getByRole('tab', { name: '上下文', exact: true }).waitFor();
  assert.equal(await page.getByRole('tab', { name: '上下文', exact: true }).getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('.revision-explorer').isVisible(), false);
  await page.getByRole('tab', { name: '上下文', exact: true }).press('End');
  assert.equal(await page.getByRole('tab', { name: 'CLM', exact: true }).getAttribute('aria-selected'), 'true');
  const policy = page.locator('.revision-policy');
  await policy.locator('summary').click();
  assert.equal(await policy.getAttribute('data-expanded'), 'true');
  assert.equal(await policy.locator('.revision-disclosure-body').evaluate(el => el.inert), false);
  const easing = await policy.locator('.revision-disclosure-body').evaluate(el => el.getAnimations().map(animation => animation.effect.getTiming().easing));
  assert.ok(easing.includes('cubic-bezier(0.215, 0.61, 0.355, 1)'), 'disclosure must reuse project cubic motion');
  await page.waitForTimeout(280);
  await policy.locator('summary').click();
  assert.equal(await policy.locator('.revision-disclosure-body').evaluate(el => el.inert), true);
  await page.waitForTimeout(280);
  assert.equal(await policy.evaluate(el => el.open), false);
  await page.locator('.revision-preserved>summary').click();
  await page.waitForTimeout(280);
  assert.equal(await page.locator('.revision-preserved .revision-disclosure-body').evaluate(el => el.inert), false);
  await page.locator('.revision-preserved>summary').click();
  await page.waitForTimeout(280);
  const live = page.getByTestId('current-revision');
  const organize = page.getByRole('button', { name: '整理上下文', exact: true });
  const start = async () => { await organize.click(); await page.getByRole('button', { name: '开始整理', exact: true }).click(); };
  const waitIdle = () => page.waitForFunction(() => !document.querySelector('.is-organizing'));
  const screenshot = async name => {
    await page.waitForTimeout(650);
    await page.screenshot({ path: `${output}/${name}.png` });
  };
  const noOverflow = async () => {
    const offenders = await page.evaluate(() => [...document.querySelectorAll('.clm-panel,.clm-preview-bar,.revision-map,.revision-timeline,.revision-token-flow,.revision-heading,.revision-document')].filter(el => el.getClientRects().length && el.scrollWidth > el.clientWidth + 1).map(el => el.className));
    assert.deepEqual(offenders, []);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  };
  await screenshot('revision-light');
  await page.getByRole('button', { name: '查看修订 r5', exact: true }).click();
  assert.match(await page.locator('.revision-selection').textContent(), /历史只读/);
  assert.equal(await live.textContent(), '当前生效 · r7');
  assert.equal(await organize.isDisabled(), true);
  await page.getByTestId('block-ctx_012').click();
  assert.match(await page.locator('.revision-diff-after').textContent(), /复用缓存方案失败/);
  await page.getByRole('button', { name: '展开宽视图' }).click();
  await screenshot('revision-history-diff');
  await noOverflow();
  const contentPicker = page.getByRole('combobox', { name: '选择内容', exact: true });
  assert.equal(await contentPicker.evaluate(element => getComputedStyle(element).appearance), 'base-select');
  await contentPicker.selectOption('ctx_015');
  await contentPicker.click();
  await contentPicker.press('Escape');
  assert.equal(await contentPicker.evaluate(element => element === document.activeElement), true);
  assert.match(await page.locator('.revision-unchanged').textContent(), /未修改/);
  await page.getByRole('button', { name: '工作内容', exact: true }).click();
  assert.match(await page.locator('.revision-text').textContent(), /pnpm test:account/);
  await page.getByRole('button', { name: '回到当前' }).click();
  await page.getByRole('button', { name: '概览', exact: true }).click();
  await page.getByRole('button', { name: '收窄面板' }).click();
  await page.getByRole('switch', { name: '启用 CLM' }).click();
  assert.equal(await organize.isDisabled(), true);
  assert.match(await page.locator('.revision-warning').textContent(), /不再使用 CLM/);
  assert.equal(await page.locator('.revision-timeline button').count(), 4);
  await page.getByRole('tab', { name: '上下文', exact: true }).click();
  assert.equal(await page.locator('.clm-usage strong').textContent(), '—');
  await page.getByRole('tab', { name: 'CLM', exact: true }).click();
  await page.getByRole('switch', { name: '启用 CLM' }).click();
  await organize.click();
  await page.getByLabel('保留重点').fill('保留失败原因');
  await page.getByLabel('保留重点').press('Escape');
  assert.equal(await page.locator('.revision-form-disclosure>div').evaluate(el => el.inert), true);
  assert.equal(await organize.evaluate(el => el === document.activeElement), true);
  await start();
  assert.equal(await page.getByRole('switch').isDisabled(), true);
  await page.getByRole('button', { name: '取消整理', exact: true }).click();
  await page.waitForTimeout(2600);
  assert.equal(await live.textContent(), '当前生效 · r7');
  await start();
  await page.getByRole('button', { name: '查看修订 r4', exact: true }).click();
  await waitIdle();
  assert.equal(await live.textContent(), '当前生效 · r8');
  assert.match(await page.locator('.revision-selection').textContent(), /r4.*历史只读/);
  await page.getByRole('button', { name: '关闭右栏' }).click();
  await page.getByLabel('消息', { exact: true }).fill('/clm');
  await page.getByLabel('消息', { exact: true }).press('Enter');
  assert.equal(await live.textContent(), '当前生效 · r8', 'closing the panel must not reset current revision');
  await page.getByRole('button', { name: '回到当前' }).click();
  assert.equal(await page.locator('[data-testid^="block-"]').count(), 2);
  await page.getByRole('tab', { name: '上下文', exact: true }).click();
  assert.equal(await page.locator('.clm-usage strong').textContent(), '38,420');
  await page.getByRole('tab', { name: 'CLM', exact: true }).click();
  await start();
  await waitIdle();
  assert.equal(await live.textContent(), '当前生效 · r8');
  assert.equal(await page.locator('.revision-timeline button').count(), 5);
  await page.getByLabel('预览场景').selectOption('failure');
  await start();
  await waitIdle();
  await page.getByRole('alert').waitFor();
  assert.equal(await live.textContent(), '当前生效 · r7');
  await page.getByRole('button', { name: '重试整理' }).click();
  await waitIdle();
  assert.equal(await live.textContent(), '当前生效 · r8');
  await page.getByLabel('预览场景').selectOption('unknown');
  assert.equal(await live.count(), 0);
  assert.equal(await page.locator('.revision-timeline').count(), 0);
  assert.equal(await organize.isDisabled(), true);
  await page.getByRole('button', { name: '重新获取' }).click();
  await page.getByLabel('预览场景').selectOption('empty');
  assert.equal(await page.locator('.revision-timeline').count(), 0);
  await page.getByLabel('预览场景').selectOption('ready');
  await page.getByRole('button', { name: '切换主题' }).click();
  await screenshot('revision-dark');
  await noOverflow();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await start();
  assert.equal(await page.locator('.revision-comparison i').last().evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.getByRole('button', { name: '取消整理', exact: true }).click();
  await page.getByRole('button', { name: '切换主题' }).click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await noOverflow();
    if (width === 390) await screenshot('revision-mobile');
    await page.getByTestId('block-ctx_008').click();
    await noOverflow();
    await page.getByRole('button', { name: '概览', exact: true }).click();
    await organize.click();
    await noOverflow();
    await page.getByLabel('保留重点').press('Escape');
  }
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  await page.goto(`${base}/tests/fixtures/clm-workspace.html?view=clm&accent=%23009688`);
  await page.waitForTimeout(500);
  const accent = await page.evaluate(() => {
    const root = getComputedStyle(document.documentElement);
    const color = selector => getComputedStyle(document.querySelector(selector)).color;
    return { primary: root.getPropertyValue('--primary').trim(), tab: color('#clm-tab-clm'), toggle: getComputedStyle(document.querySelector('.clm-switch')).backgroundColor, node: getComputedStyle(document.querySelector('.revision-timeline [aria-pressed=true] .revision-node i')).backgroundColor };
  });
  assert.equal(accent.tab, accent.primary);
  assert.equal(accent.node, accent.primary);
  assert.equal(accent.toggle, accent.primary);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('.revision-policy>summary').click();
  assert.equal(await page.locator('.revision-policy .revision-disclosure-body').evaluate(el => el.getAnimations().length), 0);
  await page.getByLabel('预览场景').selectOption('history');
  assert.equal(await page.locator('.revision-timeline button').count(), 5);
  await page.getByRole('button', { name: '查看更早修订', exact: true }).click();
  await page.getByRole('button', { name: '查看修订 r18', exact: true }).click();
  assert.match(await page.getByTestId('current-revision').innerText(), /r27/);
  assert.match(await page.locator('.revision-selection').innerText(), /r18/);
  await noOverflow();
  await page.getByRole('button', { name: '回到当前', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '查看修订 r27', exact: true }).getAttribute('aria-pressed'), 'true');
  await screenshot('revision-long-history');
  console.log('CLM revision preview passed, including 24-revision navigation and return to current.');
} finally {
  await browser?.close();
  await server?.close();
}
