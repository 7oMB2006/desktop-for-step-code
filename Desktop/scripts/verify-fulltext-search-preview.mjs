import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.DESKTOP_PREVIEW_URL || 'http://127.0.0.1:5296';
const output = 'test-results/fulltext-search';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
  const errors = [];
  const external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (!['127.0.0.1', 'localhost'].includes(new URL(request.url()).hostname)) external.push(request.url());
  });
  const screenshot = async name => {
    await page.waitForTimeout(300);
    await page.screenshot({ path: `${output}/${name}.png` });
  };
  const noOverflow = async () => {
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'page has horizontal overflow');
    const offenders = await page.locator('.fs-input,.fs-filters,.fs-result-row,.fs-topbar,.fs-preview-bar').evaluateAll(elements =>
      elements.filter(el => el.getClientRects().length && el.scrollWidth > el.clientWidth + 1).map(el => el.className));
    assert.deepEqual(offenders, [], 'component text overflows');
  };
  const choose = async (label, option) => {
    await page.getByRole('button', { name: label, exact: true }).click();
    await page.getByRole('menuitemradio', { name: option, exact: true }).click();
  };
  await page.goto(`${base}/tests/fixtures/fulltext-search.html`);
  assert.equal(await page.getByRole('button', { name: '搜索聊天记录', exact: true }).isVisible(), false);
  await page.getByRole('button', { name: '插件市场', exact: true }).waitFor();
  await page.getByRole('button', { name: '定时任务', exact: true }).waitFor();
  await screenshot('00-native-sidebar');
  await page.getByRole('button', { name: '搜索', exact: true }).click();
  const disclosure = page.locator('.fs-search-entry-disclosure');
  assert.match(await disclosure.evaluate(el => getComputedStyle(el).transitionTimingFunction), /cubic-bezier/);
  await page.waitForTimeout(80);
  const openingHeight = await disclosure.evaluate(el => el.getBoundingClientRect().height);
  await page.waitForTimeout(240);
  const expandedHeight = await disclosure.evaluate(el => el.getBoundingClientRect().height);
  assert.ok(openingHeight > 0 && openingHeight < expandedHeight, 'entry expands progressively');
  await page.getByRole('button', { name: '收起搜索', exact: true }).click();
  await page.waitForTimeout(80);
  const closingHeight = await disclosure.evaluate(el => el.getBoundingClientRect().height);
  assert.ok(closingHeight > 0 && closingHeight < expandedHeight, 'entry collapses progressively');
  await page.waitForTimeout(240);
  assert.equal(await disclosure.evaluate(el => el.getBoundingClientRect().height), 0);
  assert.equal(await page.getByRole('button', { name: '搜索聊天记录', exact: true }).isVisible(), false);
  await page.getByRole('button', { name: '搜索', exact: true }).click();
  await page.getByRole('button', { name: '搜索聊天记录', exact: true }).waitFor();
  const draft = await page.getByLabel('消息草稿').inputValue();
  await screenshot('01-entry-light');
  await noOverflow();
  await page.getByLabel('搜索会话', { exact: true }).fill('计费');
  assert.equal(await page.getByRole('region', { name: '聊天记录搜索', exact: true }).isVisible(), false);
  await screenshot('02-sidebar-query');
  await page.getByRole('button', { name: '搜索聊天记录', exact: true }).click();
  assert.equal(await page.getByLabel('搜索聊天记录关键词').inputValue(), '计费');
  await page.waitForFunction(() => document.querySelector('.fs-result-scroll').getAttribute('aria-busy') === 'false');
  assert.ok(await page.locator('.fs-result-row').count() >= 4);
  await screenshot('03-results-light');
  const input = page.getByLabel('搜索聊天记录关键词');
  await input.fill('API');
  await page.waitForFunction(() => !document.querySelector('.fs-loading') && document.querySelectorAll('.fs-result-row').length === 6);
  await page.getByRole('button', { name: /加载更多/ }).click();
  assert.equal(await page.locator('.fs-result-row').count(), 7);
  await page.setViewportSize({ width: 1360, height: 680 });
  await page.locator('#result-r2').click();
  await page.getByRole('region', { name: '匹配消息', exact: true }).waitFor();
  assert.equal(await page.locator('#hit-r2').evaluate(el => el === document.activeElement), true);
  assert.ok(await page.locator('#hit-r2 mark').count() > 0);
  await screenshot('04-message-location');
  await page.getByRole('button', { name: '返回搜索结果', exact: true }).click();
  assert.equal(await input.inputValue(), 'API');
  assert.equal(await page.locator('#result-r2').evaluate(el => el === document.activeElement), true);
  assert.ok(await page.locator('.fs-result-scroll').evaluate(el => el.scrollTop) > 0, 'search position restored');
  await page.setViewportSize({ width: 1360, height: 900 });
  await choose('筛选项目', '项目网站');
  assert.equal(await page.locator('.fs-result-row').count(), 1);
  await choose('筛选项目', '全部项目');
  await choose('筛选时间', '最近 7 天');
  assert.equal(await page.locator('.fs-result-row').count(), 6);
  await choose('筛选时间', '不限时间');
  await page.getByLabel('包含归档').check();
  await page.getByRole('button', { name: /加载更多/ }).click();
  assert.equal(await page.locator('.fs-result-row').count(), 8);
  assert.ok(await page.getByRole('region', { name: '早期账户方案', exact: true }).isVisible());
  await choose('预览状态', '索引建立中');
  assert.match(await page.locator('.fs-notice').textContent(), /尚未覆盖全部/);
  await screenshot('05-partial-index');
  await choose('预览状态', '索引不可用');
  assert.equal(await page.locator('.fs-result-row').count(), 5);
  assert.equal(await page.locator('[id^=result-]').count(), 0, 'degraded mode does not offer message positioning');
  await choose('预览状态', '查询失败');
  await page.getByRole('button', { name: '重新查询', exact: true }).click();
  await input.fill('不存在的关键词');
  await page.getByRole('heading', { name: '没有匹配记录' }).waitFor();
  await screenshot('06-no-results');
  await input.fill('');
  await page.getByRole('heading', { name: '搜索聊天记录', exact: true, level: 2 }).waitFor();
  assert.equal(await page.locator('.fs-result-row').count(), 0, 'empty query does not list all records');
  await page.getByRole('button', { name: '返回会话', exact: true }).click();
  assert.equal(await page.getByLabel('消息草稿').inputValue(), draft);
  assert.equal(await page.getByLabel('搜索会话', { exact: true }).inputValue(), '计费');
  await page.getByRole('button', { name: '搜索聊天记录', exact: true }).click();
  await page.getByRole('button', { name: '重置筛选', exact: true }).click();
  await page.getByRole('button', { name: '切换主题', exact: true }).click();
  await screenshot('07-results-dark');
  await noOverflow();
  await choose('预览状态', '查询中');
  assert.equal(await page.locator('.fs-result-scroll').getAttribute('aria-busy'), 'true');
  await screenshot('08-loading-dark');
  await choose('预览状态', '正常');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
  await page.getByRole('button', { name: '搜索', exact: true }).click();
  await page.getByLabel('搜索会话', { exact: true }).fill('计费');
  await screenshot('09-mobile-entry');
  await noOverflow();
  await page.getByRole('button', { name: '搜索聊天记录', exact: true }).click();
  assert.equal(await page.getByRole('complementary', { name: '会话导航' }).isVisible(), false);
  await screenshot('10-mobile-results');
  await noOverflow();
  await choose('筛选项目', '项目网站');
  await noOverflow();
  await choose('筛选项目', '全部项目');
  await page.locator('.fs-result-row').first().click();
  await screenshot('11-mobile-message');
  await noOverflow();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('region', { name: '聊天记录搜索', exact: true }).isVisible(), true);
  await page.getByRole('button', { name: '切换主题', exact: true }).click();
  await screenshot('12-mobile-dark');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.sidebar-search-field').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  assert.equal(await disclosure.evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  console.log('PASS: entry, queries, filters, archives, paging, message navigation, focus/scroll/draft restoration, empty/loading/partial/degraded/error states, themes, mobile, reduced motion, no external requests.');
} finally {
  await browser.close();
}
