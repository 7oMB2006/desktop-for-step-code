import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
const output = process.argv[2];
if (!output) throw new Error('Pass an evidence directory');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'no-preference' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:4197/tests/fixtures/theme-pack.html?isolated=1');
  await page.locator('.theme-stellar-stage canvas').waitFor();
  assert.equal(await page.getByRole('button', { name: '进入会话', exact: true }).count(), 0,
    'Public preview must not expose the empty lifecycle test view');
  await page.goto('http://127.0.0.1:4197/tests/fixtures/theme-pack.html?isolated=1&lifecycle=1');
  const canvas = page.locator('main .theme-stellar-stage canvas');
  await canvas.waitFor();
  await page.waitForTimeout(2500);
  const a = await canvas.screenshot();
  await page.waitForTimeout(700);
  const b = await canvas.screenshot();
  assert.ok(!a.equals(b), 'Scene should animate');
  const nonblank = await page.evaluate(async bytes => {
    const bitmap = await createImageBitmap(new Blob([new Uint8Array(bytes)], { type: 'image/png' }));
    const c = document.createElement('canvas'); c.width = bitmap.width; c.height = bitmap.height;
    const ctx = c.getContext('2d'); ctx.drawImage(bitmap, 0, 0);
    const data = ctx.getImageData(0, 0, c.width, c.height).data;
    let bright = 0, colored = 0;
    for (let i = 0; i < data.length; i += 4) {
      if (Math.max(data[i], data[i + 1], data[i + 2]) > 60) bright++;
      if (Math.max(data[i], data[i + 1], data[i + 2]) - Math.min(data[i], data[i + 1], data[i + 2]) > 25) colored++;
    }
    bitmap.close();
    return { bright, colored };
  }, [...b]);
  assert.ok(nonblank.bright > 3000 && nonblank.colored > 3000, JSON.stringify(nonblank));
  await page.screenshot({ path: join(output, 'welcome-desktop.png') });
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  const pack = page.getByRole('button', { name: '星辰巡航', exact: true });
  await pack.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.theme-pack-art img')?.naturalWidth > 0);
  await pack.hover();
  await page.locator('.theme-pack-motion canvas[data-ready=true]').waitFor();
  await page.screenshot({ path: join(output, 'theme-pack-hover.png') });
  await page.getByLabel('背景亮度').fill('60');
  await page.getByLabel('背景亮度').focus();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.theme-pack-brightness output').innerText(), '60%');
  await page.mouse.move(0, 0);
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.theme-pack-motion canvas').count(), 0);
  await pack.focus();
  await page.locator('.theme-pack-motion canvas[data-ready=true]').waitFor();
  await page.getByLabel('背景亮度').focus();
  await page.getByLabel('星海动态背景').uncheck();
  const hideOverlay = hidden => page.locator('.theme-preview-backdrop, .theme-welcome-content')
    .evaluateAll((elements, value) => elements.forEach(el => { el.style.visibility = value ? 'hidden' : ''; }), hidden);
  await hideOverlay(true);
  await page.waitForTimeout(300);
  const dim = await canvas.screenshot();
  await hideOverlay(false);
  await page.getByLabel('背景亮度').fill('110');
  await hideOverlay(true);
  await page.waitForTimeout(300);
  assert.ok(!(await canvas.screenshot()).equals(dim), 'Brightness must redraw a paused scene');
  await hideOverlay(false);
  await page.getByLabel('背景亮度').fill('60');
  await page.screenshot({ path: join(output, 'appearance-desktop.png') });
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.waitForTimeout(400);
  await page.locator('.theme-welcome-content').evaluate(el => { el.style.visibility = 'hidden'; });
  const still = await canvas.screenshot();
  await page.waitForTimeout(700);
  assert.ok((await canvas.screenshot()).equals(still), 'Motion-off should be still');
  await page.locator('.theme-welcome-content').evaluate(el => { el.style.visibility = ''; });
  await page.getByRole('button', { name: '进入会话', exact: true }).click();
  assert.equal(await canvas.count(), 0, 'Conversation must release wallpaper');
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await canvas.waitFor();
  await page.waitForTimeout(500);
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  await page.getByRole('button', { name: '原版浅色', exact: true }).click();
  await pack.scrollIntoViewIfNeeded();
  await pack.focus();
  await page.screenshot({ path: join(output, 'theme-pack-light-focus.png') });
  assert.equal(await page.locator('.theme-pack-disclosure').getAttribute('inert'), '');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  assert.equal(await canvas.count(), 0);
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  await page.getByRole('button', { name: '星辰巡航', exact: true }).click();
  await page.getByLabel('星海动态背景').check();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(700);
  await page.locator('.theme-welcome-content').evaluate(el => { el.style.visibility = 'hidden'; });
  const reduced = await canvas.screenshot();
  await page.waitForTimeout(700);
  assert.ok((await canvas.screenshot()).equals(reduced), 'Reduced motion should be still');
  await page.locator('.theme-welcome-content').evaluate(el => { el.style.visibility = ''; });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(900);
  await page.screenshot({ path: join(output, 'welcome-mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  await page.getByLabel('背景亮度').scrollIntoViewIfNeeded();
  await page.keyboard.press('Tab');
  await page.getByLabel('背景亮度').focus();
  await page.waitForTimeout(300);
  assert.ok(await page.getByLabel('背景亮度').evaluate(el => el.matches(':focus-visible')));
  await page.screenshot({ path: join(output, 'appearance-mobile.png') });
  assert.equal(await page.evaluate(() => {
    const dialog = document.querySelector('[role=dialog]');
    return dialog.scrollWidth > dialog.clientWidth;
  }), false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, nonblank, errors, output }));
} finally { await browser.close(); }
